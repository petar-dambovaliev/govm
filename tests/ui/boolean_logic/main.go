package main

func main() {
	println(true)
	println(false)
	println(!true)
	println(!false)

	println(true && true)
	println(true && false)
	println(false || true)
	println(false || false)

	println(1 == 1)
	println(1 != 2)
	println(3 > 2)
	println(2 < 3)
	println(5 >= 5)
	println(4 <= 5)
}

// Output:
//true
//false
//false
//true
//true
//false
//true
//false
//true
//true
//true
//true
//true
//true
